#!/usr/bin/env python3
"""
import_tflite.py — take a .tflite and compile it into the policy firmware.

    Drop a .tflite into  models/       then run  python3 tools/import_tflite.py

It copies the file to models/current.tflite (the record of what is actually
flashed) and regenerates the two C++ files the firmware links against:

    include/model_data.h        extern declarations
    src/policy/model_data.cpp   the model as an alignas(16) byte array

Plain Python, no dependencies — it will run with the system interpreter. If
TensorFlow happens to be importable (e.g. under ~/.venvs/tflite_conv/bin/python)
it additionally reports the operator set and checks the input/output shapes
against the firmware's expectations, which is worth the extra step: a model whose
dims do not match robot_config.h will compile fine and then fail at boot.
"""

import argparse
import os
import shutil
import sys

# Repo layout, relative to this script.
TOOLS_DIR   = os.path.dirname(os.path.abspath(__file__))
PROJECT_DIR = os.path.dirname(TOOLS_DIR)
MODELS_DIR  = os.path.join(PROJECT_DIR, "models")
CURRENT     = os.path.join(MODELS_DIR, "current.tflite")
HPP_PATH    = os.path.join(PROJECT_DIR, "include", "model_data.h")
CPP_PATH    = os.path.join(PROJECT_DIR, "src", "policy", "model_data.cpp")

# Must match include/robot_config.h.
EXPECT_IN  = 10
EXPECT_OUT = 1

# huge_app.csv app partition, minus room for the Arduino core + TFLM (~350 KB).
APP_PARTITION_BYTES = 3 * 1024 * 1024
FIRMWARE_OVERHEAD   = 400 * 1024


def pick_source(arg: str | None) -> str:
    """Use the given path, else find exactly one .tflite in models/."""
    if arg:
        if not os.path.isfile(arg):
            sys.exit(f"error: {arg} not found")
        return arg

    candidates = [
        os.path.join(MODELS_DIR, f)
        for f in sorted(os.listdir(MODELS_DIR))
        if f.endswith(".tflite") and f != "current.tflite"
    ]
    if not candidates:
        if os.path.isfile(CURRENT):
            return CURRENT
        sys.exit(f"error: no .tflite found in {MODELS_DIR}\n"
                 f"       drop one in there, or pass a path explicitly")
    if len(candidates) > 1:
        names = "\n  ".join(os.path.basename(c) for c in candidates)
        sys.exit(f"error: several .tflite files in models/, pass one explicitly:\n  {names}")
    return candidates[0]


def check_magic(data: bytes) -> None:
    """TFLite flatbuffers carry 'TFL3' at offset 4. Cheap guard against a
    mis-named .pt or .onnx, which would otherwise produce a byte array that
    compiles and then fails GetModel() at runtime."""
    if len(data) < 8 or data[4:8] != b"TFL3":
        sys.exit("error: this does not look like a .tflite "
                 "(missing 'TFL3' identifier at offset 4)")


def inspect(path: str) -> None:
    """Optional richer check, only if a TFLite runtime is importable."""
    try:
        try:
            from ai_edge_litert.interpreter import Interpreter
        except ImportError:
            from tensorflow.lite import Interpreter
    except ImportError:
        print("  (install tensorflow or ai-edge-litert, or run this with")
        print("   ~/.venvs/tflite_conv/bin/python, for an op + shape check)")
        return

    interp = Interpreter(model_path=path)
    interp.allocate_tensors()

    inp = interp.get_input_details()[0]
    out = interp.get_output_details()[0]
    print(f"  input   {inp['name']}  shape={[int(x) for x in inp['shape']]}  {inp['dtype'].__name__}")
    print(f"  output  {out['name']}  shape={[int(x) for x in out['shape']]}  {out['dtype'].__name__}")

    try:
        # "DELEGATE" is the host interpreter reporting XNNPACK, not an operator
        # in the file; there is no TFLM kernel by that name.
        ops = sorted({d["op_name"] for d in interp._get_ops_details()} - {"DELEGATE"})
        print(f"  ops     {', '.join(ops)}")
        print("  -> these must all be registered in src/policy/policy.cpp")
    except Exception:
        pass

    n_in, n_out = int(inp["shape"][-1]), int(out["shape"][-1])
    if n_in != EXPECT_IN or n_out != EXPECT_OUT:
        print()
        print(f"  WARNING: model is {n_in} -> {n_out}, firmware expects "
              f"{EXPECT_IN} -> {EXPECT_OUT}.")
        print( "  The firmware refuses to start on a mismatch rather than reading")
        print( "  past the input tensor. If this is the 11-D variant, OBS_DIM_CFG in")
        print( "  include/robot_config.h and the observation builder both need updating.")


def write_c_array(data: bytes) -> None:
    with open(HPP_PATH, "w") as f:
        f.write(
            "// Generated by tools/import_tflite.py — do not edit.\n"
            "#pragma once\n"
            "#include <cstddef>\n"
            "#include <cstdint>\n\n"
            "extern const unsigned char g_model[];\n"
            "extern const size_t g_model_len;\n"
        )

    with open(CPP_PATH, "w") as f:
        f.write(
            "// Generated by tools/import_tflite.py — do not edit.\n"
            f"// Source: models/current.tflite ({len(data):,} bytes)\n"
            '#include "model_data.h"\n\n'
            "// alignas(16): TFLite Micro reads the flatbuffer in place and traps\n"
            "// on an unaligned access.\n"
            "alignas(16) const unsigned char g_model[] = {\n"
        )
        for i in range(0, len(data), 12):
            f.write("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 12]) + ",\n")
        f.write("};\n\n")
        f.write(f"const size_t g_model_len = {len(data)};\n")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("tflite", nargs="?", default=None,
                    help="path to a .tflite (default: the one in models/)")
    args = ap.parse_args()

    src = pick_source(args.tflite)
    with open(src, "rb") as f:
        data = f.read()
    check_magic(data)

    print(f"importing {os.path.relpath(src, PROJECT_DIR)}  "
          f"({len(data):,} bytes / {len(data)/1024:.1f} KB)")
    inspect(src)

    if os.path.abspath(src) != os.path.abspath(CURRENT):
        shutil.copyfile(src, CURRENT)
        print(f"\n  -> models/current.tflite")

    write_c_array(data)
    print(f"  -> include/model_data.h")
    print(f"  -> src/policy/model_data.cpp")

    total = len(data) + FIRMWARE_OVERHEAD
    print(f"\n  estimated flash use {total/1024:.0f} KB of "
          f"{APP_PARTITION_BYTES/1024:.0f} KB app partition")
    if total > APP_PARTITION_BYTES:
        print("  WARNING: will not fit. Quantize the model or enlarge the partition.")

    print("\nnext:  pio run -e policy -t upload")
    print("note:  inference speed is bounded by flash bandwidth (~6.9 MB/s on this")
    print("       board), so roughly 0.15 ms per KB of model. The 200 Hz control")
    print("       loop allows 5 ms total.")


if __name__ == "__main__":
    main()
